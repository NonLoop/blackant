(function () {
  function detectLang() {
    try {
      var saved = localStorage.getItem("ba-lang");
      if (saved === "zh" || saved === "en") return saved;
    } catch (e) {}
    return (navigator.language || "zh").toLowerCase().indexOf("zh") === 0 ? "zh" : "en";
  }

  var lang = detectLang();

  function apply(l) {
    lang = l;
    try { localStorage.setItem("ba-lang", l); } catch (e) {}
    document.documentElement.setAttribute("lang", l === "zh" ? "zh-CN" : "en");
    var dict = window.I18N[l];
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] != null) el.innerHTML = dict[key];
    });
    document.querySelectorAll("[data-i18n-text]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-text");
      if (dict[key] != null) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
    });
    document.title =
      l === "zh"
        ? document.body.getAttribute("data-title-zh") || "黑蚁工作室 BlackAnt Studio — 精品应用系列"
        : document.body.getAttribute("data-title-en") || "BlackAnt Studio — Crafted iOS Apps";
    document.querySelectorAll(".lang-btn").forEach(function (b) {
      b.textContent = l === "zh" ? "EN" : "中文";
    });
  }

  window.__setLang = function (l) { apply(l); };
  window.__getLang = function () { return lang; };

  document.addEventListener("DOMContentLoaded", function () { apply(lang); });

  window.__toggleLang = function (btn, event) {
    if (event) event.stopPropagation();
    apply(lang === "zh" ? "en" : "zh");
    btn.blur();
  };
})();
